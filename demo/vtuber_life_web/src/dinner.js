async function loadVrmAgent(config) {
  const gltf = await loader.loadAsync(config.model);
  const vrm = gltf.userData.vrm;
  VRMUtils.removeUnnecessaryVertices(gltf.scene);
  VRMUtils.combineSkeletons(gltf.scene);
  VRMUtils.rotateVRM0(vrm);
  vrm.scene.traverse((obj) => {
    obj.frustumCulled = false;
    if (obj.isMesh) {
      obj.castShadow = true;
      obj.receiveShadow = false;
      if (obj.material) { obj.material.envMapIntensity = 0.5; obj.material.needsUpdate = true; }
    }
  });
  const box = new THREE.Box3().setFromObject(vrm.scene);
  const size = box.getSize(new THREE.Vector3());
  vrm.scene.scale.setScalar(config.targetHeight / Math.max(0.1, size.y));
  const scaled = new THREE.Box3().setFromObject(vrm.scene);
  vrm.scene.userData.floorOffset = -scaled.min.y;
  scene.add(vrm.scene);
  // eye-tracking target: eyes lead the head toward whoever is being looked at
  const gazeObj = new THREE.Object3D();
  scene.add(gazeObj);
  if (vrm.lookAt) vrm.lookAt.target = gazeObj;
  return {
    ...config, vrm, root: vrm.scene, headWorld: new THREE.Vector3(),
    gazeObj, gazePos: new THREE.Vector3(), gazeWeight: 0, smoothHeading: null,
  };
}

async function loadRobotAgent(config) {
  const gltf = await loader.loadAsync(config.model);
  const root = gltf.scene;
  root.traverse((obj) => {
    obj.frustumCulled = false;
    if (obj.isMesh) { obj.castShadow = true; }
  });
  const box = new THREE.Box3().setFromObject(root);
  const size = box.getSize(new THREE.Vector3());
  root.scale.setScalar(config.targetHeight / Math.max(0.1, size.y));
  const scaled = new THREE.Box3().setFromObject(root);
  root.userData.floorOffset = -scaled.min.y;
  scene.add(root);

  const mixer = new THREE.AnimationMixer(root);
  const actions = {};
  gltf.animations.forEach((clip) => { actions[clip.name] = mixer.clipAction(clip); });
  const idle = actions.Idle;
  if (idle) { idle.play(); }
  let headBone = null;
  root.traverse((obj) => { if (!headBone && obj.isBone && /head/i.test(obj.name)) headBone = obj; });
  return {
    ...config, root, mixer, actions, headBone,
    currentAction: 'Idle', headWorld: new THREE.Vector3(),
    gazePos: new THREE.Vector3(), gazeWeight: 0, smoothHeading: null,
  };
}

