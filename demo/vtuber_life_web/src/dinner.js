function animate() {
  const t = window.__recordTime !== undefined ? Number(window.__recordTime) : (performance.now() / 1000) % DURATION;
  updateScene(t);
  composer.render();
  window.__soulforgeFrameReady = true;
  requestAnimationFrame(animate);
}

function updateScene(t) {
  const dt = THREE.MathUtils.clamp(t - lastAnimT >= 0 ? t - lastAnimT : 1 / 24, 0.001, 0.12);
  const beat = BEATS.find((b) => t >= b.start && t < b.end) ?? null;
  const frames = {};
  for (const agent of Object.values(agents)) {
    frames[agent.id] = motionFrame(agent, t);
  }
  applyBeat(beat, frames, t);

  for (const agent of Object.values(agents)) {
    const frame = frames[agent.id];

    // temporal smoothing: bodies turn over ~0.3s instead of snapping on beat edges
    if (frame.moving || agent.smoothHeading == null) {
      agent.smoothHeading = frame.heading;
    } else {
      agent.smoothHeading = lerpAngle(agent.smoothHeading, frame.heading, 1 - Math.exp(-dt * 7));
    }
    frame.heading = agent.smoothHeading;

    // gaze fades in/out and the aim point glides between targets
    const headY = (agent.root.userData.floorOffset ?? 0) + agent.targetHeight * 0.9;
    const ahead = new THREE.Vector3(
      frame.x - Math.sin(frame.heading) * 2.5, headY, frame.z - Math.cos(frame.heading) * 2.5,
    );
    const aim = frame.gazeTarget ?? ahead;
    if (agent.gazeWeight <= 0.001 && frame.gazeTarget) agent.gazePos.copy(aim);
    agent.gazePos.lerp(aim, 1 - Math.exp(-dt * 8));
    agent.gazeWeight += ((frame.gazeTarget ? 1 : 0) - agent.gazeWeight) * (1 - Math.exp(-dt * 6));
    if (agent.gazeObj) agent.gazeObj.position.copy(agent.gazePos);

    agent.root.position.set(frame.x, agent.root.userData.floorOffset ?? 0, frame.z);
    agent.root.rotation.y = frame.heading;
    if (agent.kind === 'vrm') {
      animateVrm(agent, frame, t);
    } else {
      animateRobot(agent, frame, t, dt);
    }
    agent.headWorld.set(frame.x, headY, frame.z);
  }

  updateSceneProps(t, frames);
  updateHud(beat, frames, t);
  updateCamera(beat, t);
  lastAnimT = t;
}

// ---------------------------------------------------------------------------
// motion: waypoint interpolation + beat-driven gaze / turn-taking
// ---------------------------------------------------------------------------
function motionFrame(agent, t) {
  const wp = agent.waypoints;
  let a = wp[0]; let b = wp[wp.length - 1];
  for (let i = 0; i < wp.length - 1; i += 1) {
    if (t >= wp[i].t && t <= wp[i + 1].t) { a = wp[i]; b = wp[i + 1]; break; }
  }
  const span = Math.max(0.001, b.t - a.t);
  const raw = THREE.MathUtils.clamp((t - a.t) / span, 0, 1);
  const k = smoothstep(raw);
  const moving = raw > 0 && raw < 1 && (Math.hypot(b.x - a.x, b.z - a.z) > 0.05);
  const x = THREE.MathUtils.lerp(a.x, b.x, k);
  const z = THREE.MathUtils.lerp(a.z, b.z, k);
  let heading = moving ? facing(b.x - a.x, b.z - a.z) : lerpAngle(a.h, b.h, k);
  return {
    x, z, heading, moving,
    activity: agent.activity(t),
    speaking: false, listening: false,
    gazeTarget: null, // Vector3
    bodyTurn: 0,
  };
}

function applyBeat(beat, frames, t) {
  if (!beat) return;
  const speakerFrame = frames[beat.speaker];
  if (speakerFrame) {
    speakerFrame.speaking = beat.text.length > 0;
    const target = beat.targets[0];
    const pos = targetPosition(target, frames);
    if (pos && !speakerFrame.moving) {
      speakerFrame.gazeTarget = pos;
      // partially turn the body toward the target, fully turn the head
      const want = facing(pos.x - speakerFrame.x, pos.z - speakerFrame.z);
      const turn = beat.speaker === 'pipo' ? 0.9 : (speakerFrame.activity === 'talk' ? 0.5 : 0.35);
      speakerFrame.heading = lerpAngle(speakerFrame.heading, want, turn);
    }
  }
  beat.targets.forEach((id) => {
    const frame = frames[id];
    if (!frame || frame.moving) return;
    frame.listening = true;
    frame.beatStart = beat.start;
    const pos = targetPosition(beat.speaker, frames);
    if (pos) {
      frame.gazeTarget = pos;
      const want = facing(pos.x - frame.x, pos.z - frame.z);
      frame.heading = lerpAngle(frame.heading, want, frame.activity === 'talk' ? 0.45 : 0.2);
    }
  });
  // non-speaking third agent glances at the speaker too (soft social presence)
  Object.entries(frames).forEach(([id, frame]) => {
    if (id === beat.speaker || beat.targets.includes(id) || frame.moving) return;
    const pos = targetPosition(beat.speaker, frames);
    if (pos) frame.gazeTarget = pos;
  });
}

function targetPosition(id, frames) {
  if (id === 'user') return USER_POS.clone();
  const frame = frames[id];
  const agent = agents[id];
  if (!frame || !agent) return null;
  return new THREE.Vector3(frame.x, (agent.root.userData.floorOffset ?? 0) + agent.targetHeight * 0.88, frame.z);
}

