let shotStartT = 0;

function updateCamera(beat, t) {
  let shotName = beat?.camera ?? lastShotName;
  if (t < 1.0) shotName = 'wide';
  if (!SHOTS[shotName]) shotName = 'wide';
  if (shotName !== lastShotName) shotStartT = t;
  lastShotName = shotName;
  const shot = SHOTS[shotName];

  let px = shot.pos[0]; let py = shot.pos[1]; let pz = shot.pos[2];
  if (shotName === 'wide_end') {
    const k = THREE.MathUtils.clamp((t - 27.4) / 2.6, 0, 1);
    pz -= k * 0.75; py += k * 0.1; // slow pull-back finale
  } else {
    // gentle eased push-in toward the subject over the life of the shot
    const p = THREE.MathUtils.clamp((t - shotStartT) / 5.0, 0, 1);
    const k = p * p * (3 - 2 * p);
    const push = (shot.push ?? 0.16) * k;
    const dir = new THREE.Vector3(shot.look[0] - px, shot.look[1] - py, shot.look[2] - pz).normalize();
    px += dir.x * push; py += dir.y * push; pz += dir.z * push;
  }
  // subtle handheld drift
  px += Math.sin(t * 0.5) * 0.02;
  py += Math.sin(t * 0.37 + 1.0) * 0.012;
  pz += Math.cos(t * 0.43) * 0.02;

  camera.fov = shot.fov;
  camera.position.set(px, py, pz);
  camera.lookAt(shot.look[0], shot.look[1], shot.look[2]);
  camera.updateProjectionMatrix();
}

